#!/usr/bin/env python3
"""Scan compose env vars and provide manifest/env-check utilities."""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import sys
from collections import Counter
from typing import Iterable


REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
CORE_COMPOSE = REPO_ROOT / "bootstrap" / "compose" / "core" / "docker-compose.yml"
EDGE_COMPOSE = REPO_ROOT / "bootstrap" / "compose" / "edge" / "docker-compose.yml"
ENV_VAR_PATTERN = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-[^}]*)?\}")
SECRET_HINT_TOKENS = ("PASSWORD", "TOKEN", "SECRET", "KEY")
REQUIRED_ENV_VARS = [
    "PUBLIC_DOMAIN",
    "POSTGRES_USER",
    "POSTGRES_PASSWORD",
    "POSTGRES_DB",
    "MINIO_ROOT_USER",
    "MINIO_ROOT_PASSWORD",
    "VAULTWARDEN_ADMIN_TOKEN",
    "TUNNEL_TOKEN",
]


def extract_vars_from_text(text: str) -> list[str]:
    return ENV_VAR_PATTERN.findall(text)


def scan_compose_file(path: pathlib.Path) -> dict[str, int]:
    if not path.is_file():
        raise RuntimeError(f"compose file missing: {path}")
    counter: Counter[str] = Counter(extract_vars_from_text(path.read_text(encoding="utf-8", errors="replace")))
    return dict(sorted(counter.items()))


def scan_compose_env_vars() -> dict[str, dict[str, int]]:
    return {
        "core": scan_compose_file(CORE_COMPOSE),
        "edge": scan_compose_file(EDGE_COMPOSE),
    }


def is_likely_secret(var_name: str) -> bool:
    upper = var_name.upper()
    return any(token in upper for token in SECRET_HINT_TOKENS)


def render_env_manifest(scan: dict[str, dict[str, int]], required_vars: Iterable[str]) -> str:
    required_set = set(required_vars)

    def section(title: str, vars_map: dict[str, int]) -> list[str]:
        lines = [f"## {title}", "", "| Variable | Count | Required | Likely Secret |", "| --- | ---: | --- | --- |"]
        for var_name in sorted(vars_map):
            required = "yes" if var_name in required_set else "no"
            secret = "yes" if is_likely_secret(var_name) else "no"
            lines.append(f"| `{var_name}` | {vars_map[var_name]} | {required} | {secret} |")
        if not vars_map:
            lines.append("| _none_ | 0 | no | no |")
        lines.append("")
        return lines

    out: list[str] = ["# Environment Variables Manifest", ""]
    out.extend(section("Core compose variables", scan.get("core", {})))
    out.extend(section("Edge compose variables", scan.get("edge", {})))
    out.append("Generated by `python3 ops/bin/env_scan.py manifest`.")
    out.append("")
    return "\n".join(out)


def env_check_lines(explain: bool = False) -> tuple[list[str], bool]:
    scan = scan_compose_env_vars()
    lines: list[str] = []
    failed = False
    for var_name in REQUIRED_ENV_VARS:
        present = bool(os.environ.get(var_name, ""))
        status = "OK" if present else "MISSING"
        if explain:
            core_count = scan.get("core", {}).get(var_name, 0)
            edge_count = scan.get("edge", {}).get(var_name, 0)
            lines.append(f"{var_name}: {status} — core:{core_count} edge:{edge_count}")
        else:
            lines.append(f"{var_name}: {status}")
        if not present:
            failed = True
    lines.append("ENV-CHECK: FAIL" if failed else "ENV-CHECK: PASS")
    return lines, failed


def cmd_scan_json() -> int:
    print(json.dumps(scan_compose_env_vars(), sort_keys=True))
    return 0


def cmd_manifest(output_path: str | None) -> int:
    scan = scan_compose_env_vars()
    text = render_env_manifest(scan, REQUIRED_ENV_VARS)
    if output_path:
        path = pathlib.Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"[PASS] Wrote env manifest: {path}")
    else:
        print(text, end="")
    return 0


def cmd_env_check(explain: bool) -> int:
    lines, failed = env_check_lines(explain=explain)
    for line in lines:
        print(line)
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compose environment scanner")
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("scan-json", help="Print compose env variable counts as JSON")
    manifest_parser = subparsers.add_parser("manifest", help="Generate markdown environment manifest")
    manifest_parser.add_argument("--output", help="Optional file path to write markdown")
    env_check_parser = subparsers.add_parser("env-check", help="Validate required env vars")
    env_check_parser.add_argument("--explain", action="store_true", help="Include core/edge usage counts")

    args = parser.parse_args(argv)
    try:
        if args.command == "scan-json":
            return cmd_scan_json()
        if args.command == "manifest":
            return cmd_manifest(args.output)
        if args.command == "env-check":
            return cmd_env_check(args.explain)
        parser.print_help()
        return 1
    except RuntimeError as exc:
        print(f"[FAIL] {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
